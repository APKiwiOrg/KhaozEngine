using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using KhaozEngine.Physics.Bepu;
using Xunit;

namespace KhaozEngine.Tests.Locomotion.Contacts;

public partial class SupportNeighborhoodEquivalenceTests
{
    [Fact]
    public void RepresentedGoldenChangesHaveIndependentPerRowDerivations()
    {
        Assert.Equal("67DA85EBB30678C4168299A33115385C70546CA5B4A7A726B19749102D468FBA",
            Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(SupportEquivalenceFields.Fixture(SupportEquivalenceFields.BaselineName)))));
        var baseline = SupportEquivalenceFields.Baseline().ToDictionary(r => r.Name);
        var table = new List<string>
        {
            "# Represented support golden row derivations", "",
            "Generated by RepresentedGoldenChangesHaveIndependentPerRowDerivations under frozen questions.",
            "The baseline was frozen at 9e63657a7 and every row re-hashed to its original digest.", "",
            "| Row | Old digest | New digest | Scene digest | Frozen question digest | Changed field classes | Independent derivation |",
            "| --- | --- | --- | --- | --- | --- | --- |"
        };
        var counts = new SortedDictionary<string, int>();
        var unresolved = new List<string>();
        int changed = 0, protectedChanges = 0;
        var anchors = new SupportEquivalenceQueryAnchors();
        anchors.Generate((q, world, lease) =>
        {
            var old = baseline[q.Row];
            Assert.Equal(old.Scene, q.SceneDigest);
            Assert.Equal(old.Question, JsonSerializer.Serialize(SupportEquivalenceQueryAnchors.Bits.Encode(q)));
            var current = SupportEquivalenceFields.Read(q, world, lease);
            if (current.Line == old.Line) return;
            changed++;
            bool guarded = q.Row.StartsWith("feature/", StringComparison.Ordinal) || q.Row.StartsWith("fan/", StringComparison.Ordinal) ||
                q.Row.StartsWith("mesh/", StringComparison.Ordinal) && int.Parse(q.Row.Split('/')[1]) % 2 == 0;
            if (guarded) protectedChanges++;
            var before = old.Fields.ToDictionary(f => f.Name);
            var after = current.Fields.ToDictionary(f => f.Name);
            string[] classes = before.Keys.Union(after.Keys).Where(name => !before.TryGetValue(name, out var a) ||
                !after.TryGetValue(name, out var b) || a != b).Select(name => after.TryGetValue(name, out var f) ? f.Class : before[name].Class)
                .Distinct().Order().ToArray();
            foreach (string kind in classes) counts[kind] = counts.GetValueOrDefault(kind) + 1;
            string derivation;
            try
            {
                Assert.False(guarded, "Protected row changed");
                SupportEquivalenceRepresentedOracle.AssertAnswer(q, (BepuPhysicsWorld)world, lease);
                derivation = "CC-3/CC-5/CC-9. Installed represented source, independent membership, witness, normal, joins and both slope contributions verified";
            }
            catch (Exception exception)
            {
                derivation = "UNDERIVABLE. " + exception.Message.Replace('\n', ' ').Replace('\r', ' ').Replace('|', '/');
                unresolved.Add(q.Row + " " + derivation);
            }
            string questionDigest = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(old.Question)));
            table.Add($"| {q.Row} | {old.Hash} | {current.Hash} | {q.SceneDigest} | {questionDigest} | {string.Join(", ", classes)} | {derivation} |");
        });
        anchors.Complete();
        table.AddRange(["", $"Changed rows {changed}. Protected changes {protectedChanges}. Underivable rows {unresolved.Count}.", ""]);
        foreach (var (kind, count) in counts) table.Add($"- {kind}: {count}");
        string? path = Environment.GetEnvironmentVariable("KHAOZENGINE_SUPPORT_REPRESENTED_PROOF");
        if (!string.IsNullOrEmpty(path)) File.WriteAllLines(path, table);
        output.WriteLine($"Changed {changed}, protected {protectedChanges}, underivable {unresolved.Count}.");
        foreach (var (kind, count) in counts) output.WriteLine($"{kind}: {count}");
        Assert.Equal(0, protectedChanges);
        Assert.True(unresolved.Count == 0, string.Join("\n", unresolved));
    }
}
