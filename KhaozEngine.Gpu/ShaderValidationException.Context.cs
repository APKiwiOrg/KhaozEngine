namespace KhaozEngine.Gpu;

public sealed partial class ShaderValidationException
{
    /// <summary>Adds compiler-boundary context while preserving the reason and every diagnostic identifier.
    /// A consumer exception with no reason receives CrossCompileFailed. Existing context takes precedence.</summary>
    public ShaderValidationException WithContext(string message, string? label = null,
        GpuShaderStages? stage = null, string? target = null)
        => new(Reason ?? ShaderValidationRefusal.CrossCompileFailed, message, this)
        {
            Label = Label ?? label,
            ExecutionMode = ExecutionMode,
            Stage = Stage ?? stage,
            Target = Target ?? target,
            Operation = Operation,
            ResultCode = ResultCode,
            Diagnostic = Diagnostic,
            Profile = Profile,
            Semantic = Semantic,
            FirstMissingIndex = FirstMissingIndex,
            RepairSourcePaths = RepairSourcePaths,
            Set = Set,
            Binding = Binding,
            ElementCount = ElementCount,
            Space = Space,
            ArgumentIndex = ArgumentIndex,
            DeclaredSet = DeclaredSet,
            DeclaredBinding = DeclaredBinding,
            EmittedSet = EmittedSet,
            EmittedBinding = EmittedBinding,
            ExpectedIndex = ExpectedIndex,
            Slot = Slot,
            DeclaredKind = DeclaredKind,
            DeclaredBufferKind = DeclaredBufferKind,
            EmittedKind = EmittedKind,
            PipelineKind = PipelineKind,
            NativeDiagnosticMissing = NativeDiagnosticMissing,
            EntryPointKeyword = EntryPointKeyword,
            HelperKind = HelperKind,
            Policy = Policy,
            DeclaredLayoutCount = DeclaredLayoutCount,
            ReflectedLayoutCount = ReflectedLayoutCount,
            DeclaredElementCount = DeclaredElementCount,
            ReflectedElementCount = ReflectedElementCount,
            ReflectedKind = ReflectedKind,
            EntryPoint = EntryPoint,
            SourceOrigin = SourceOrigin,
            StageCount = StageCount,
            Stages = Stages,
            LayoutCount = LayoutCount,
            StreamCount = StreamCount,
            LowestStreamIndex = LowestStreamIndex,
            BufferTableSize = BufferTableSize,
            NativeResourceKind = NativeResourceKind,
            SourceDeclaration = SourceDeclaration,
            NativeBaseType = NativeBaseType,
            ComponentCount = ComponentCount,
            WordOffset = WordOffset,
            WordCount = WordCount,
            ModuleWordCount = ModuleWordCount,
            ByteLength = ByteLength,
            MinimumHeaderBytes = MinimumHeaderBytes,
            WordBytes = WordBytes,
            ActualMagic = ActualMagic,
            ExpectedMagic = ExpectedMagic,
            HResult = HResult,
        };
}
