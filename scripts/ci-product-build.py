#!/usr/bin/env python3
"""Select and audit Product CI roots, and write temporary build and test solutions."""
import argparse
import json
import os
from pathlib import Path
import posixpath
import runpy
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOLUTION = ROOT / 'KhaozEngine.slnx'
OVERLAYS = {
    'sql-accounts': ('accounts',),
    'sql-catalog': ('server',),
    'sql-server': ('server',),
    'water-kernel': ('tile-world-physics', 'tile-world-physics-floating-point'),
}


def closure(graph, projects):
    reached = set()
    pending = list(projects)
    while pending:
        project = pending.pop()
        if project not in reached:
            reached.add(project)
            pending.extend(graph[project])
    return reached


def audit_inventory(manifest, canonical, outside):
    graph = {}
    tests = set()
    for project in sorted(canonical | outside):
        document = ET.parse(ROOT / project)
        folder = posixpath.dirname(project)
        graph[project] = {posixpath.normpath(posixpath.join(folder, item.attrib['Include'].replace('\\', '/')))
                          for item in document.iter('ProjectReference') if 'Include' in item.attrib}
        if project in canonical and (
            any(item.attrib.get('Include') == 'Microsoft.NET.Test.Sdk' for item in document.iter('PackageReference'))
            or any(item.text == 'true' for item in document.iter('IsTestProject'))
        ):
            tests.add(project)
    for project, dependencies in graph.items():
        missing = dependencies - graph.keys()
        if missing:
            raise ValueError(f'{project} references projects missing from the inventory: {sorted(missing)}')

    for segment, entry in manifest.items():
        if not isinstance(entry, dict) or not isinstance(entry.get('roots'), list) or not all(
            isinstance(root, str) for root in entry['roots']
        ):
            raise ValueError(f'{segment} must list its project paths')
        roots = entry['roots']
        expected_role = (
            'overlay' if segment in OVERLAYS else 'tooling' if segment == 'tooling'
            else 'compile' if segment.startswith('compile-') else 'test'
        )
        expected_count = len(OVERLAYS.get(segment, ())) if expected_role in ('overlay', 'tooling') else 1
        if entry.get('role') != expected_role or len(roots) != expected_count:
            raise ValueError(f'{segment} must have role {expected_role} and {expected_count} roots')
    for role, expected in (('test', tests), ('compile', outside | (canonical - closure(graph, tests)))):
        actual = [entry['roots'][0] for entry in manifest.values() if entry['role'] == role]
        if len(set(actual)) != len(actual):
            raise ValueError(f'Duplicate {role} roots: {sorted(root for root in set(actual) if actual.count(root) > 1)}')
        if expected != set(actual):
            raise ValueError(f'{role} inventory differs: missing {sorted(expected - set(actual))}, '
                             f'unexpected {sorted(set(actual) - expected)}')
    for overlay, segments in OVERLAYS.items():
        expected = [root for segment in segments for root in manifest[segment]['roots']]
        if overlay not in manifest or manifest[overlay]['roots'] != expected:
            raise ValueError(f'{overlay} must use {expected}')
    if 'tooling' not in manifest:
        raise ValueError('The tooling segment is missing')
    return graph


def audit_rules(manifest, graph):
    # Only project-directory rows are generated by the reference graph. Keep the manually audited
    # full and ignore overrides and the tooling row independent of that graph.
    rows = {}
    for line in (ROOT / '.github/ci-scope.txt').read_text().splitlines():
        name, _, globs = line.partition(':')
        name = name.strip()
        if name and not name.startswith('#') and name not in {'full', 'ignore'}:
            rows.setdefault(name, set()).update(globs.split())
    if rows.keys() != manifest.keys():
        raise ValueError(f'Scope and inventory segments differ: {sorted(rows.keys() ^ manifest.keys())}')
    for segment, entry in manifest.items():
        if entry['role'] == 'tooling':
            continue
        expected = {f'{posixpath.dirname(path)}/**' for path in closure(graph, entry['roots'])}
        if rows[segment] != expected:
            raise ValueError(f'{segment} scope differs from its references: '
                             f'add {sorted(expected - rows[segment])}, remove {sorted(rows[segment] - expected)}')


def write_solution(path, selected):
    tree = ET.parse(SOLUTION)
    pending = set(selected)
    for parent in list(tree.iter()):
        for project in parent.findall('Project'):
            source = project.attrib['Path'].replace('\\', '/')
            if source not in pending:
                parent.remove(project)
                continue
            project.set('Path', Path(os.path.relpath(ROOT / source, path.parent)).as_posix())
            pending.remove(source)
    for source in sorted(pending):
        ET.SubElement(tree.getroot(), 'Project', {'Path': Path(os.path.relpath(ROOT / source, path.parent)).as_posix()})
    ET.indent(tree, space='  ')
    tree.write(path, encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('full', choices=('true', 'false'))
    parser.add_argument('segments', help='JSON array emitted by ci-scope')
    parser.add_argument('--solutions', type=Path, help='Write solutions into this directory')
    parser.add_argument('--scope-reason', default='', help='ci-scope diagnosis when its rules were unavailable')
    args = parser.parse_args()

    try:
        full = args.full == 'true'
        manifest = json.loads((ROOT / '.github/ci-projects.json').read_text())
        segments = json.loads(args.segments)
        if not isinstance(segments, list) or not all(isinstance(name, str) for name in segments):
            raise ValueError('ci-scope segments must be an array of strings')
        if not full and set(segments) - manifest.keys():
            raise ValueError(f'Unknown scope segments: {sorted(set(segments) - manifest.keys())}')
        canonical = {item.attrib['Path'].replace('\\', '/') for item in ET.parse(SOLUTION).iter('Project')}
        outside = set(runpy.run_path(str(ROOT / 'scripts/outside-solution-projects.py'))['outside'](ROOT))
        graph = audit_inventory(manifest, canonical, outside)
        if not (full and args.scope_reason.startswith(('Full run: no rules file', 'Full run: rules file line '))):
            audit_rules(manifest, graph)
        selected = manifest if full else set(segments)
        tests = sorted({root for name in selected if manifest[name]['role'] == 'test'
                        for root in manifest[name]['roots']})
        build = sorted(canonical | outside if full else {root for name in selected for root in manifest[name]['roots']})
        overlays = sorted(set(selected) & OVERLAYS.keys())
        if args.solutions:
            args.solutions.mkdir(parents=True, exist_ok=True)
            write_solution(args.solutions / 'product.slnx', build)
            write_solution(args.solutions / 'tests.slnx', tests)
            write_solution(args.solutions / 'water.slnx', manifest['water-kernel']['roots'])
        print(json.dumps({'build_roots': build, 'test_roots': tests,
                          'outside_roots': sorted(outside.intersection(build)), 'overlays': overlays}))
    except (KeyError, OSError, TypeError, ValueError, ET.ParseError) as error:
        parser.error(str(error))


if __name__ == '__main__':
    main()
